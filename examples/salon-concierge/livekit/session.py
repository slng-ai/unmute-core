# --- templates ---------------------------------------------------------------
_TEMPLATE = re.compile(r"\{\{\s*([a-z_][a-z0-9_]*)\s*\}\}")


def _render(
    text: str, userdata: CallState | None, *, quote_values: bool = False, site: str = ""
) -> str:
    """Substitute each variable token from the session userdata.

    Only substituted values are URL-encoded, never the surrounding literal.

    Args:
        text: The text holding `{{name}}` tokens.
        userdata: The session state to read them from, or None to leave the text alone.
        quote_values: URL-encode each substituted value.
        site: Where the text is used, for saved-value path lookups.

    Returns:
        The text with each token replaced.
    """
    if userdata is None:
        return text

    def _one(match: re.Match[str]) -> str:
        # Through CallState.render, which walks a path emitted as one flat name,
        # renders a declared value as compact JSON and an empty one as words.
        value = CallState.render(userdata, match.group(1), site)
        return quote(value, safe="") if quote_values else value

    return _TEMPLATE.sub(_one, text)


def _refusal(tool: str, userdata: CallState, needed: list[tuple[str, str]]) -> str:
    """Refuse a call whose injected variables are still unset.

    The model is told what to do about each one, and no half-formed request is
    ever sent.

    Args:
        tool: The tool the model tried to call.
        userdata: The session state holding the variables.
        needed: Each required variable with the hint for getting it.

    Returns:
        The refusal text, or an empty string when nothing is missing.
    """
    unset = [
        (name, hint)
        for name, hint in needed
        if userdata.lookup(name)[1] in (None, "")
        # A value the caller has not agreed to is present and not usable. Without
        # this, a pre-fetched number would reach somebody else's record: the
        # request would go out against a proposal rather than a fact.
        or userdata.is_unconfirmed(name)
    ]
    if not unset:
        return ""
    names = ", ".join(name for name, _ in unset)
    hints = " ".join(f"{name}: {hint}" for name, hint in unset if hint)
    return f"cannot call {tool} yet: {names} not set. {hints}".strip()


# Pre-fetch, generated by internal/generate/prefetch.go.
#
# Facts that are knowable before the greeting are resolved here, once per call,
# so the model is never asked to discover them. An entry whose inputs are empty
# is skipped and the values keep their declared defaults, which is what makes a
# package that pre-fetches a carrier fact still work on a route that supplies
# none. Nothing here can fail a call.
_PREFETCH_BUDGET_S = 2.0
_PREFETCH_VALUE_MAX = 512
_PREFETCH_DAYS = (
    "Monday",
    "Tuesday",
    "Wednesday",
    "Thursday",
    "Friday",
    "Saturday",
    "Sunday",
)
# Keypad spellings of the words a carrier substitutes when a number is
# withheld. They pass the shape check below because they are the right shape:
# digits, and about as many as a phone number has.
_PREFETCH_WITHHELD = (
    "266696687",  # anonymous
    "7378742833",  # restricted
    "8656696",  # unknown
    "86282452253",  # unavailable
    "7748283",  # private
)


def _prefetch_number(name: str, value: object) -> str:
    """Read a phone number, or "" when the carrier sent a placeholder instead.

    A withheld caller ID arrives three ways: empty, as the word "anonymous", or
    as the keypad digits of a word an upstream carrier sent, which is shaped like
    a real number. All three mean the same thing and all three must skip the
    entry, because a value that reaches a prompt is a value the agent reads back
    to the caller as their own number.

    Args:
        name: Name of the call fact, used in the log line.
        value: What the carrier supplied.

    Returns:
        The number as text, or an empty string when it is absent or a placeholder.
    """
    text = ("" if value is None else str(value)).strip()
    # E.164: a plus, then 8 to 15 digits. Anything else was not a number, which
    # covers "anonymous", "unavailable", "restricted" and an empty string alike.
    #
    # Spelled out rather than a regex so this block needs no import of its own,
    # and isascii() beside isdigit() because isdigit() is true of digits in other
    # scripts, which no carrier sends and no downstream tool would accept.
    digits = text.removeprefix("+")
    if not (
        text.startswith("+")
        and digits.isascii()
        and digits.isdigit()
        and 8 <= len(digits) <= 15
    ):
        if text:
            logger.info(
                f"prefetch: {name} was not a phone number, treating it as absent"
            )
        return ""
    # The digit form. Equal, or the start of a longer spelling, which is what a
    # word passed on truncated looks like.
    #
    # Only that direction. Matching a value that *begins* with a spelling would
    # throw away real numbers: "unknown" spells 8656696, and +86 5669 6xxx is an
    # ordinary Chinese mobile. A word shorter than eight digits therefore never
    # matches here, and does not need to: the shape check above already refused
    # it for being too short to be a number.
    if any(spelled.startswith(digits) for spelled in _PREFETCH_WITHHELD):
        logger.info(
            f"prefetch: {name} is a withheld-caller-ID placeholder, treating it as absent"
        )
        return ""
    return text


def _prefetch_call_facts(call_context: dict | None) -> dict:
    """Merge the call's own facts with the local seed, which fills only gaps.

    UNMUTE_CALL_FACTS is what `unmute dev --source name=value` sets. The
    carrier wins wherever it supplied a value: a seed stands in for a fact it
    could not supply, and never overrides one it did, so a stale value in a .env
    cannot quietly reshape a real call.

    Merging here rather than at each call site is deliberate. This driver starts a
    session from four different places, and a merge written four times is a merge
    that disagrees with itself in one of them.

    Args:
        call_context: The facts the carrier or dispatch supplied, if any.

    Returns:
        The facts, with the seed's values added where the carrier gave none.
    """
    facts = dict(call_context or {})
    seeded = os.environ.get("UNMUTE_CALL_FACTS")
    if not seeded:
        return facts
    try:
        values = json.loads(seeded)
        facts |= {name: value for name, value in values.items() if not facts.get(name)}
    except (ValueError, TypeError, AttributeError):
        logger.warning(
            "UNMUTE_CALL_FACTS is not a JSON object of call facts; ignoring it"
        )
    return facts


def _prefetch_bounded(name: str, value: object) -> object:
    """Bound one pre-fetched value, and say so when it is shortened.

    The length is only knowable here, at run time, so this cannot be a
    compile-time refusal. Silence is the one thing it must not be.

    Args:
        name: Name of the declared value, used in the warning.
        value: What the lookup produced.

    Returns:
        The value, cut to the bound when it is text and longer than that.
    """
    if not isinstance(value, str) or len(value) <= _PREFETCH_VALUE_MAX:
        return value
    logger.warning(
        f"prefetch: {name} was {len(value)} characters and is cut to "
        f"{_PREFETCH_VALUE_MAX}; a value this long stops the prompt being cached"
    )
    return value[:_PREFETCH_VALUE_MAX]


def _prefetch_outcome(task: asyncio.Task) -> None:
    """Retrieve a finished lookup's exception so asyncio never reports it unread.

    Args:
        task: The finished lookup task.
    """
    if not task.cancelled():
        task.exception()


async def _prefetch_wait(work: object, deadline: float) -> dict:
    """Run one lookup, giving up when the startup budget runs out.

    Args:
        work: The lookup coroutine.
        deadline: The event loop time the whole block has to finish by.

    Returns:
        The lookup's JSON result.

    Raises:
        TimeoutError: If the lookup was not done by the deadline.
    """
    # work is a coroutine, and naming that type would need an import this block cannot add.
    task = asyncio.create_task(work)  # ty: ignore[invalid-argument-type]
    task.add_done_callback(_prefetch_outcome)
    try:
        done, _ = await asyncio.wait(
            {task}, timeout=max(0, deadline - asyncio.get_running_loop().time())
        )
        if not done or asyncio.get_running_loop().time() >= deadline:
            raise TimeoutError
        return task.result()
    finally:
        if not task.done():
            task.cancel()


async def _prefetch(state: CallState, call_context: dict | None) -> None:
    """Resolve every declared pre-fetch entry, inside one startup budget.

    Args:
        state: The call's shared state object, filled in place.
        call_context: The facts the carrier or dispatch supplied, if any.
    """
    deadline = asyncio.get_running_loop().time() + _PREFETCH_BUDGET_S
    call_context = _prefetch_call_facts(call_context)
    # Entries run in the order agent.yaml lists them. Nothing here is sorted or
    # reordered: an entry reading a value a later entry assigns was refused at
    # compile time, so by here the order is known good.

    if asyncio.get_running_loop().time() >= deadline:
        return
    try:
        _now = datetime.now(ZoneInfo("Europe/Madrid"))
        state.save_batch(
            {
                "booking_date": _prefetch_bounded(
                    "booking_date", _now.date().isoformat()
                ),
                "booking_weekday": _prefetch_bounded(
                    "booking_weekday", _PREFETCH_DAYS[_now.weekday()]
                ),
                "salon_local_time": _prefetch_bounded(
                    "salon_local_time", _now.strftime("%H:%M")
                ),
            },
            inputs=[],
        )
        logger.info(
            "prefetch today: resolved booking_date, booking_weekday, salon_local_time"
        )
    except TimeoutError:
        logger.warning(
            "prefetch today: startup budget expired; booking_date, booking_weekday, salon_local_time keep their defaults"
        )
        return
    except Exception:  # noqa: BLE001, RUF100 - a failed pre-fetch is logged, never fatal; ruff only knows stdlib logging's exception()
        logger.exception(
            "prefetch today: failed; booking_date, booking_weekday, salon_local_time keep their defaults"
        )

    if asyncio.get_running_loop().time() >= deadline:
        return
    try:
        _value = (call_context or {}).get("from_number")
        _value = _prefetch_number("from_number", _value)
        if _value in (None, ""):
            logger.info("prefetch caller: skipped, the call carries no from_number")
        else:
            state.save_batch(
                {"customer_phone": _prefetch_bounded("customer_phone", _value)},
                inputs=[],
            )
            logger.info(
                "prefetch caller: resolved customer_phone, awaiting confirmation"
            )
    except TimeoutError:
        logger.warning(
            "prefetch caller: startup budget expired; customer_phone keeps its default"
        )
        return
    except Exception:  # noqa: BLE001, RUF100 - a failed pre-fetch is logged, never fatal; ruff only knows stdlib logging's exception()
        logger.exception("prefetch caller: failed; customer_phone keeps its default")


# --- job metadata ------------------------------------------------------------
def _livekit_job_metadata(raw: str) -> dict:
    """Parse the job metadata LiveKit hands to this worker.

    Args:
        raw: The metadata string, possibly empty.

    Returns:
        The metadata object, empty when none was sent.

    Raises:
        RuntimeError: The metadata is not a JSON object.
    """
    if not raw:
        return {}
    try:
        metadata = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise RuntimeError("LiveKit job metadata must be valid JSON") from exc
    if not isinstance(metadata, dict):
        raise RuntimeError("LiveKit job metadata must be a JSON object")
    return metadata


# --- dispatched input variables ----------------------------------------------
def _dispatched_call_start(metadata: dict | None = None) -> dict:
    """Read the input variables that arrive with the dispatch.

    They come in the job metadata in production, or in UNMUTE_CALL_START for a
    local `unmute dev --var` session.

    Args:
        metadata: The parsed job metadata, if any.

    Returns:
        The variables. Their types are checked when _hydrate_call_start saves
        them.

    Raises:
        RuntimeError: A required value is missing, or UNMUTE_CALL_START is not a
            JSON object.
    """
    values = dict((metadata or {}).get("call_start", {}))
    raw = os.getenv("UNMUTE_CALL_START")
    if raw:
        try:
            supplied = json.loads(raw)
        except json.JSONDecodeError as exc:
            raise RuntimeError("UNMUTE_CALL_START must be valid JSON") from exc
        if not isinstance(supplied, dict):
            raise RuntimeError("UNMUTE_CALL_START must be a JSON object")
        # The dispatch wins: env is the local stand-in for it.
        values = supplied | values
    missing: list[str] = []
    if missing:
        raise RuntimeError("Missing call_start fields: " + ", ".join(missing))
    return values


def _hydrate_call_start(userdata: CallState, values: dict) -> None:
    """Save the dispatched input variables onto the session state.

    Args:
        userdata: The state to fill.
        values: The variables from _dispatched_call_start.

    Raises:
        RuntimeError: A value does not fit its declared type.
    """
    userdata.save_call_start(values)
